// Builds the unpacked extension: node ext/build.mjs <outDir> [--test <fixtureOrigin> <mobBase>]
// Keys come from tools/aquarius/.keys.json (gitignored), never from the repo.
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync, readFileSync, copyFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const HERE = dirname(fileURLToPath(import.meta.url));
const [out, flag, origin, mobTest] = process.argv.slice(2);
if (!out) { console.error("usage: node build.mjs <outDir> [--test <origin> <mob>]"); process.exit(1); }
const test = flag === "--test";
const BUILD = process.env.AQ_BUILD || "2";
const keysFile = join(HERE, "../.keys.json");
const keys = test ? { feedKey: "aq-key-test", linkKey: "lk-test" } : JSON.parse(readFileSync(keysFile, "utf8"));
const chatMatches = ["https://claude.ai/*"].concat(test ? ["http://127.0.0.1/*"] : []);
const config = { build: BUILD, mob: test ? mobTest : "https://mob.gardenbuddystore.workers.dev", feedKey: keys.feedKey, linkKey: keys.linkKey,
  startUrl: test ? `${origin}/search` : "https://www.google.com/", chatMatches, lang: "en-US", ...(test ? { tickMs: 500, cardMs: 6000, magicLife: 4000 } : {}) };
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });
writeFileSync(join(HERE, "src/config.js"), `// generated by build.mjs\nexport const CONFIG = ${JSON.stringify(config, null, 1)};\n`);
const common = { bundle: true, write: true, target: "chrome120", nodePaths: [join(HERE, "../../../node_modules")], legalComments: "none" };
await build({ ...common, entryPoints: [join(HERE, "src/content.js")], outfile: join(out, "content.js"), format: "iife", minify: true });
// not minified: functions handed to chrome.scripting are serialised from their source text
await build({ ...common, entryPoints: [join(HERE, "src/background.js")], outfile: join(out, "background.js"), format: "esm", minify: false });
rmSync(join(HERE, "src/config.js"));
const manifest = {
  manifest_version: 3, name: "Aquarius", short_name: "Aquarius", version: `1.0.${BUILD}`, version_name: `build ${BUILD}`,
  description: "Aquarius, the CEO genie: floats over claude.ai, types into the chat, listens for his name, and works a tab of his own.",
  icons: { 16: "icon-16.png", 32: "icon-32.png", 48: "icon-48.png", 128: "icon-128.png" },
  action: { default_title: `Aquarius · build ${BUILD} (click to bring him back)`, default_icon: { 16: "icon-16.png", 32: "icon-32.png" } },
  background: { service_worker: "background.js", type: "module" },
  content_scripts: [{ matches: chatMatches, ...(test ? { exclude_matches: ["http://127.0.0.1/old*"] } : {}), js: ["content.js"], run_at: "document_idle" }],
  permissions: ["storage", "tabs", "scripting", "alarms"],
  host_permissions: ["<all_urls>"],
};
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2));
for (const n of [16, 32, 48, 128]) { const f = join(HERE, `../design/icon-${n}.png`); if (existsSync(f)) copyFileSync(f, join(out, `icon-${n}.png`)); else if (!test) throw new Error(`missing ${f}`); }
console.log(`  ok  extension build ${BUILD} -> ${out}${test ? " (test)" : ""}`);
