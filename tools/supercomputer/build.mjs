// Builds the unpacked extension:  node build.mjs <outDir> [--test]
//   SC_BUILD     build number shown on screen (default below)
//   SC_UPDATE_URL  address of version.json {build, zip, notes} for "update ready" (empty = updates off)
// --test adds http://127.0.0.1/* so the end-to-end test page (a stand-in for Kraken Pro) gets the widget.
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FEEDS } from "./src/lib/news.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const [out, flag] = process.argv.slice(2);
if (!out) { console.error("usage: node build.mjs <outDir> [--test]"); process.exit(1); }
const test = flag === "--test";
export const BUILD = process.env.SC_BUILD || "1";
const updateUrl = process.env.SC_UPDATE_URL || "";
const config = { build: BUILD, updateUrl, ...(test ? { moversDelayMs: 1500, scanGapMs: 400 } : {}) };
const matches = ["https://pro.kraken.com/*"].concat(test ? ["http://127.0.0.1/*"] : []);
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });
writeFileSync(join(HERE, "src/config.js"), `// generated by build.mjs\nexport const CONFIG = ${JSON.stringify(config)};\n`);
const common = { bundle: true, write: true, target: "chrome120", legalComments: "none", nodePaths: [join(HERE, "../../node_modules")] };
try {
  await build({ ...common, entryPoints: [join(HERE, "src/content.js")], outfile: join(out, "content.js"), format: "iife", minify: true });
  await build({ ...common, entryPoints: [join(HERE, "src/background.js")], outfile: join(out, "background.js"), format: "esm", minify: true });
} finally { rmSync(join(HERE, "src/config.js"), { force: true }); }
const feedHosts = [...new Set(Object.values(FEEDS).flat().map((f) => new URL(f.url).origin + "/*"))];
const manifest = {
  manifest_version: 3, name: "supercomputer", short_name: "supercomputer", version: `1.0.${BUILD}`, version_name: `build ${BUILD}`,
  description: "Eyes only on Kraken Pro: 5 and 15 minute reads, a plan sized to your stop, movers, news and Grok. Never trades, never reads your account.",
  icons: { 16: "icon-16.png", 32: "icon-32.png", 48: "icon-48.png", 128: "icon-128.png" },
  action: { default_title: `supercomputer · build ${BUILD}`, default_icon: { 16: "icon-16.png", 32: "icon-32.png" } },
  background: { service_worker: "background.js", type: "module" },
  content_scripts: [{ matches, js: ["content.js"], run_at: "document_idle" }],
  permissions: ["storage", "alarms", "downloads"],
  host_permissions: ["https://api.kraken.com/*", "https://futures.kraken.com/*", ...feedHosts, ...(updateUrl ? [new URL(updateUrl).origin + "/*"] : [])],
};
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2));
for (const n of [16, 32, 48, 128]) copyFileSync(join(HERE, `design/icons/icon-${n}.png`), join(out, `icon-${n}.png`));
console.log(`  ok  supercomputer build ${BUILD} -> ${out}${test ? " (test)" : ""}`);
